"""Write dist/spog-config.js — the console's runtime config — from the deploy settings.

The bundle carries no broker and no bus key (src/platform/runtime-config.ts).
A deployment names them here: SPOG_BROKER and SPOG_BUS_KEY from SETUP/.env or
the CI secrets (deploy.env). When neither is set the checked-in
public/spog-config.js (which names nothing) ships unchanged, and the console
talks to /mqtt on its own origin in plaintext.
"""

import json
import os

from deploy.constants import DIST_DIR

FILE = 'spog-config.js'


def render(env):
    """The spog-config.js text for these settings, or None when there is nothing to say."""
    cfg = {}
    if env.get('SPOG_BROKER'):
        cfg['broker'] = env['SPOG_BROKER']
    if env.get('SPOG_BUS_KEY'):
        cfg['busKey'] = env['SPOG_BUS_KEY']
    if not cfg:
        return None
    return ('/* GENERATED by SETUP/deploy/runtime_config.py at deploy time — not in git. */\n'
            f'window.SPOG_CONFIG = {json.dumps(cfg)};\n')


def write_runtime_config(project_dir, env):
    text = render(env)
    if text is None:
        print("No SPOG_BROKER / SPOG_BUS_KEY — shipping the default spog-config.js (same-origin /mqtt, plaintext).")
        return False
    with open(os.path.join(project_dir, DIST_DIR, FILE), 'w') as f:
        f.write(text)
    print(f"Runtime config written → {DIST_DIR}/{FILE} ({', '.join(k for k in ('broker', 'busKey') if k in text)}).")
    return True
